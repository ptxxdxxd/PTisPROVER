"""Regenerate the example reports and examples/README.md from examples/*.toml.

python scripts/build_examples.py          # rewrite the files
python scripts/build_examples.py --check  # exit 1 if any committed file is stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from ptisprover import __version__, load_rubric
from ptisprover.prover import prove
from ptisprover.render import CHECK_NAMES, render_html, render_text
from ptisprover.report import Report, Status

ROOT = Path(__file__).resolve().parent.parent
EXAMPLES = ROOT / "examples"
REPORTS = EXAMPLES / "reports"


def headline(report: Report) -> str:
    """The most severe finding, for the summary table."""
    for status in (Status.FAIL, Status.INCONCLUSIVE, Status.WARN):
        for finding in report.findings:
            if finding.status is status:
                return f"{CHECK_NAMES[finding.check]}: {finding.message}"
    return "every check passed"


def expected_files() -> dict[Path, str]:
    files: dict[Path, str] = {}
    rows = []
    for path in sorted(EXAMPLES.glob("*.toml")):
        rubric = load_rubric(path)
        report = prove(rubric).report
        stem = path.stem
        files[REPORTS / f"{stem}.txt"] = render_text(report, __version__)
        files[REPORTS / f"{stem}.json"] = report.to_json()
        files[REPORTS / f"{stem}.html"] = render_html(report, rubric, __version__)
        rows.append(
            f"| [{path.name}]({path.name}) | {rubric.description} | **{report.verdict}** "
            f"| {headline(report)} | [text](reports/{stem}.txt), [JSON](reports/{stem}.json), "
            f"[HTML](reports/{stem}.html) |"
        )
    files[EXAMPLES / "README.md"] = "\n".join(
        [
            "# Examples",
            "",
            "Synthetic rubrics for grading model outputs, each with a flaw a reviewer could miss.",
            "The table and the reports are generated by `scripts/build_examples.py`.",
            "",
            "| Rubric | Grades | Verdict | Main finding | Reports |",
            "|---|---|---|---|---|",
            *rows,
            "",
        ]
    )
    return files


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="report stale files, change nothing")
    args = parser.parse_args(argv)
    stale = []
    for path, text in expected_files().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        stale.append(path)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    orphans = sorted(set(REPORTS.glob("*")) - set(expected_files()))
    for path in stale:
        print(f"{'stale' if args.check else 'wrote'}: {path.relative_to(ROOT)}")
    for path in orphans:
        print(f"no source for: {path.relative_to(ROOT)}")
    return 1 if args.check and (stale or orphans) else 0


if __name__ == "__main__":
    sys.exit(main())
